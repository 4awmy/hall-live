import {mkdirSync,writeFileSync,copyFileSync,readFileSync} from 'node:fs';
import {loadPresentation} from '../presentation.mjs';
const out=new URL('../_site/',import.meta.url);
mkdirSync(out,{recursive:true});
const deck=loadPresentation().map(({notes,timing,revision,...slide})=>slide);
writeFileSync(new URL('deck.json',out),JSON.stringify(deck));
for(const file of ['app.js','style.css','logos.js'])copyFileSync(new URL('../'+file,import.meta.url),new URL(file,out));
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8').replace('<script type="module"','<script>window.HALL_STATIC=true;</script><script type="module"');
writeFileSync(new URL('index.html',out),html);
writeFileSync(new URL('.nojekyll',out),'');
console.log('Built '+deck.length+' presentation slides. No speaker notes, credentials or runtime data.');
